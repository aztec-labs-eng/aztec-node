function release_packages {
  echo "Computing packages to publish..."
  local packages=$(get_projects topological)

  # Scoped release (see ci3/release_prep_package_json): only the @aztec deps local to this
  # workspace are co-published at $1; foundation deps keep the version the root resolutions
  # field pins them to.
  local resolutions
  resolutions="$(jq -c '.resolutions // {}' package.json)"
  export NPM_RELEASE_RESOLUTIONS="$resolutions"

  # Validate every manifest before anything is published: deploy_npm applies the same
  # scoped-release rules per package inside the loop below, where a failure would abort
  # the release with earlier packages already live on npm.
  echo "Validating package manifests..."
  for package in $packages; do
    (cd $package && release_prep_package_json --check "$1")
  done

  local package_list=()
  for package in $packages; do
    (cd $package && retry "deploy_npm $1")
    local package_name=$(jq -r .name "$package/package.json")
    package_list+=("$package_name@$1")
  done
  # Smoke test the deployed packages.
  local dir=$(mktemp -d)
  cd "$dir"
  do_or_dryrun npm init -y
  # NOTE: originally this was on one line, but sometimes snagged downloading end-to-end (most recently published package).
  # --no-audit --no-fund: npm's implicit audit re-scans the whole cumulative tree on every install, dominating
  # release time. Dependency vulnerabilities are covered by the weekly socket-fix workflow instead.
  # npm publish is eventually consistent: a just-published version can take a few minutes to
  # become installable, so give each install a ~5 minute window instead of the default ~10s.
  for package in "${package_list[@]}"; do
    RETRY_ATTEMPTS=10 RETRY_SLEEP=30 retry "do_or_dryrun npm install --no-audit --no-fund $package"
  done
  rm -rf "$dir"
}

function release {
  echo_header "yarn-project release"
  release_packages "${REF_NAME#v}"
}

case "$cmd" in
  "clean")
    [ -n "${1:-}" ] && cd $1
    git clean -fdx
    ;;
  "clean-lite")
    # Preserve gitignored fixture dirs that are populated by sibling builds and
    # consumed concurrently by parallel test commands. Wiping them mid-test
    # yanks files out from under readers (e.g. the pinned Chonk inputs download).
    files=$(git ls-files --ignored --others --exclude-standard | grep -vE '(node_modules/|^\.yarn/|^tmp/|^end-to-end/example-app-ivc-inputs-out/|^end-to-end/ultrahonk-bench-inputs/|^end-to-end/dumped-avm-circuit-inputs/)' || true)
    if [ -n "$files" ]; then
      echo "$files" | xargs rm -rf
    fi
    ;;
  "")
    build
    ;;
  "compile")
    if [ -n "${1:-}" ]; then
      compile_project ::: "$@"
    else
      get_projects | compile_project
    fi
    ;;
  instrumented_profile)
    # Automatically hooks sites with benchmarking instrumentation.
    if [ "$#" -gt 1 ]; then
      echo "Usage: ./bootstrap.sh profile <command>"
      exit 1
    fi
    cmd=$1
    # Refuse to continue if there are uncommitted changes to tracked files.
    if [ -n "$(git status --porcelain | grep -v '^??')" ]; then
      echo "Please commit or stash your changes before running this command."
      exit 1
    fi
    rm -f profile-*.json
    echo "NOTE: If you interrupt this you may have a dirty git state or build state. Otherwise it will clean up."
    ( cd ./scripts/instrumenting-profiler && npm install )
    ./scripts/instrumenting-profiler/instrument.sh
    denoise "./bootstrap.sh compile"
    pwd=$(pwd)
    cleanup_instrumentation() {
